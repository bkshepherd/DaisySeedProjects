#!/usr/bin/env sh
# Writes models_list.inc: an #include for every models/*.h (in file-name order, which is the order of the MODEL parameter's choices)
# and the table kNamA2Models[] with one entry per file. The file is only rewritten when its content changes, so make does not rebuild for nothing.
# Run by the Makefile and the host test scripts; run it by hand after adding or removing a model if you build some other way.
cd "$(dirname "$0")" || exit 1
tmp=$(mktemp)
{
    echo "// Generated by update_models.sh from the files in models/ - do not edit."
    for f in $(ls models/*.h 2>/dev/null | LC_ALL=C sort); do
        echo "#include \"$f\""
    done
    echo
    echo "inline constexpr NamA2ModelEntry kNamA2Models[] = {"
    for f in $(ls models/*.h 2>/dev/null | LC_ALL=C sort); do
        stem=$(basename "$f" .h)
        case "$stem" in
        *[!A-Za-z0-9_]*) echo "update_models.sh: $f: use only letters, digits and _ in the file name" >&2; rm -f "$tmp"; exit 1 ;;
        esac
        echo "    {nam_model_$stem::kName, nam_model_$stem::kWeights, nam_model_$stem::kOutputGain},"
    done
    echo "};"
} >"$tmp"
if cmp -s "$tmp" models_list.inc; then rm -f "$tmp"; else mv "$tmp" models_list.inc; fi
