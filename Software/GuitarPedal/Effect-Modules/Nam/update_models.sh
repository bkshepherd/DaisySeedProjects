#!/usr/bin/env sh
# Writes models_list.inc: an #include for every models/*.h (in file-name order, which is the order of the MODEL parameter's choices)
# and the table kNamA2Models[] with one entry per file: the name, the weights and the output gain (kOutputGain) of the model, all from its
# file. The file is only rewritten when its content changes, so make does not rebuild for nothing.
#
#   update_models.sh                   run by hand in a terminal: regenerates the list, then asks whether to calibrate the output gains
#   update_models.sh --calibrate [dB]  regenerates the list and calibrates without asking
#   update_models.sh --no-calibrate    regenerates the list only; this is what the Makefile and the host test scripts run
#
# Calibration is optional: it measures every model on the host (tests/host/calibrate_nam.sh) and sets kOutputGain in each model file so that
# all models give the same level, dB RMS (default +12) for the guitar-like test signal at the reference input level, at default settings with
# the IR cab Off. It takes a minute (it builds the NAM module for the PC) and needs g++. Do it after adding a model or when you want to level
# the models again.
export LC_ALL=C # decimal points in the numbers, whatever the locale
cd "$(dirname "$0")" || exit 1
list=models_list.inc
target=12
case "${1:-}" in
--calibrate) calibrate=1; [ -n "${2:-}" ] && target=$2 ;;
--no-calibrate) calibrate=0 ;;
"") calibrate=ask ;;
*) echo "usage: update_models.sh [--calibrate [target dB] | --no-calibrate]" >&2; exit 2 ;;
esac

files=$(ls models/*.h 2>/dev/null | LC_ALL=C sort)
for f in $files; do
    case "$(basename "$f" .h)" in
    *[!A-Za-z0-9_]*) echo "update_models.sh: $f: use only letters, digits and _ in the file name" >&2; exit 1 ;;
    esac
done

tmp=$(mktemp)
{
    echo "// Generated by update_models.sh from the files in models/ - do not edit."
    for f in $files; do
        echo "#include \"$f\""
    done
    echo
    echo "inline constexpr NamA2ModelEntry kNamA2Models[] = {"
    for f in $files; do
        stem=$(basename "$f" .h)
        echo "    {nam_model_$stem::kName, nam_model_$stem::kWeights, nam_model_$stem::kOutputGain},"
    done
    echo "};"
} >"$tmp"
if cmp -s "$tmp" $list; then rm -f "$tmp"; else mv "$tmp" $list; fi

if [ $calibrate = ask ]; then
    # only when a person is at the keyboard: not under make (its stdout is a pipe), not in a script
    [ -t 0 ] && [ -t 1 ] && [ -n "$files" ] || exit 0
    printf "Calibrate the output gains of the models so they all give the same level (about a minute)? [y/N] "
    read -r answer
    case "$answer" in
    [yY] | [yY][eE][sS]) calibrate=1 ;;
    *) exit 0 ;;
    esac
fi
[ $calibrate = 1 ] || exit 0

# --- calibration: measure with the gains in the files, scale each by the distance to the target, write them to the files, measure again ---
measure() { sh ../../tests/host/calibrate_nam.sh; }
gain_of() { sed -n 's/.*kOutputGain = \([0-9.eE+-]*\)f;.*/\1/p' "models/$1.h"; }
echo "Measuring the models (target $target dB)..."
before=$(measure) || { echo "update_models.sh: the measurement failed" >&2; exit 1; }
set -- $files
echo "$before" | while read -r idx name db; do
    stem=$(basename "$(eval echo \"\${$((idx + 1))}\")" .h)
    old=$(gain_of "$stem")
    [ -n "$old" ] || { echo "update_models.sh: models/$stem.h has no 'kOutputGain = <number>f;' line" >&2; exit 1; }
    new=$(awk -v o="$old" -v l="$db" -v t="$target" 'BEGIN { printf "%.4f", o * 10 ^ ((t - l) / 20) }')
    case "$new" in
    [0-9]*.[0-9]*) ;;
    *) echo "update_models.sh: no gain could be computed for $name (measured '$db')" >&2; exit 1 ;;
    esac
    sed -i "s/\(kOutputGain = \)[0-9.eE+-]*f;/\1${new}f;/" "models/$stem.h"
    printf '  %-24s %+7.2f dB  gain %sf -> %sf\n' "$name" "$db" "$old" "$new"
done || exit 1
echo "Measuring again with the new gains..."
measure | while read -r idx name db; do printf '  %-24s %+7.2f dB\n' "$name" "$db"; done
echo "The gains are kOutputGain in the files in models/; rebuild to use them."
