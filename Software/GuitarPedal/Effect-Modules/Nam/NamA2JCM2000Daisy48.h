//   - headW / headB / headScale
//
// This spends about 4 KB more RAM than v4, but avoids repeated raw-model
// address arithmetic and raw-layout loads inside the callback. It keeps the
// compact v2/v4 loop kernels and constexpr topology, so .text should remain
