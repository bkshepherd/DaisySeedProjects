/*
    NamA2JCM2000Daisy48_minram_v16_k6_current_direct.h

    Single-header, allocation-free A2 Nano WaveNet runtime for Daisy / STM32H7.

    Model embedded:
      Marshall JCM2000 DSL100_A2.nam
      SlimmableContainer low-CPU submodel: A2 WaveNet, 3 channels, 1871 weights.
      Block size: 48 samples. Mono input -> mono output.

    Usage:
      - Call load_default_model() once from setup / Init, not from the audio callback.
      - Call process_block_48(in, out) from the audio callback with exactly 48 samples.
      - For stereo processing, create two A2State objects and one shared A2SharedWeights.

    v16 change:
      - branchless leaky from v15
      - K=6 dual kernel uses direct current tap for non-layer-0 layers

    Hot-path design:
      - no heap
      - no std::vector
      - no modulo / division in the audio callback
      - C=3 hard-unrolled matrix-vector math
      - 16-tap head uses bitmask wrapping
      - hybrid ring histories: pow2 rings for small layers, exact rings for large layers
      - flattened contiguous history arena
*/

