// CPU-aggressive compact history policy.
// Use exact ring sizes plus one safety column. The extra column allows the
// K=6 dual-sample kernel to write samples n and n+1 before accumulating both
// without overwriting the oldest tap needed by sample n.
// Cost versus exact rings: 23 layers * 3 floats = 276 bytes.
static constexpr int exact_cols_for_layer(int i) noexcept
{
    return (kKernelSizes[i] - 1) * kDilations[i] + 2;
}

static constexpr int compute_exact_history_columns() noexcept
{
    int total = 0;
    for (int i = 0; i < kNumLayers; ++i)
        total += exact_cols_for_layer(i);
    return total;
}

