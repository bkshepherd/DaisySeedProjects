// Raw model layout helpers.
// Layout:
//   rechannel[3]
//   per layer:
//      conv[out][in][tap]
//      convB[3]
//      mixinW[3]
//      l1x1[out][in]
//      l1x1B[3]
//   headW[in][tap]
//   headB
//   headScale
inline int raw_layer_base(int li) noexcept
{
    int off = 3;
    for(int i = 0; i < li; ++i)
        off += kKernelSizes[i] * 9 + 18;
    return off;
}

